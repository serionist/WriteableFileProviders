using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Reflection;
using Amazon.S3;
using Microsoft.VisualStudio.TestTools.UnitTesting;
using Newtonsoft.Json.Linq;
using WriteableFileProviders.AmazonS3;
using WriteableFileProviders.AzureBlob;
using WriteableFileProviders.Box;
using WriteableFileProviders.GoogleCloudStorage;
using WriteableFileProviders.Minio;
using WriteableFileProviders.SharePoint;

namespace WriteableFileProviders.Tests.Serialization
{
    /// <summary>
    /// Pins the configuration shape (AGENTS.md, one-way doors): the "Type" key and every options property name, as
    /// consumers have stored them. The files in Golden/ were written by the Newtonsoft-based serializer of the
    /// 2026.10.10.x line; they must never be regenerated by a later serializer, only read by it.
    /// </summary>
    [TestClass]
    public class ConfigurationShapeTests
    {
        private static string Golden(string name) =>
            File.ReadAllText(Path.Combine(AppContext.BaseDirectory, "Serialization", "Golden", name));

        // Fake values only: the shape matters, not the content.
        public static IEnumerable<object[]> Shapes => new[]
        {
            new object[] { "WriteableAzureBlobFileProvider", new AzureFileProviderOptions { AccountName = "account", AccountKey = "ZmFrZS1rZXk=", ContainerName = "container", Protocol = "https", Url = "account.blob.example.net", RootDirectoryPath = "root/dir" } },
            new object[] { "WriteableAmazonS3FileProvider", new AmazonS3FileProviderOptions("root/dir", "test-access-key", "test-secret-key", "bucket", "eu-west-1", S3StorageClass.StandardInfrequentAccess) },
            new object[] { "WriteableMinioFileProvider", new MinioFileProviderOptions("root/dir", "minio.example.net:9000", "test-access-key", "test-secret-key", "bucket") { UseSSL = true } },
            new object[] { "WriteableGoogleCloudStorageFileProvider", new GoogleCloudStorageFileProviderOptions("bucket", "service@project.example", "fake-private-key", "project", "root/dir") { CredentialsJson = "{}" } },
            new object[] { "WriteableBoxFileProvider", new BoxFileProviderOptions("client-id", "client-secret", "123456", "public-key-id", "fake-private-key", "passphrase", "0") { RootDirectoryPath = "root/dir" } },
            new object[] { "WriteableSharePointFileProvider", new SharePointFileProviderOptions("https://tenant.sharepoint.example/sites/files", "Documents", "00000000-0000-0000-0000-000000000001", "00000000-0000-0000-0000-000000000002", "client-secret", "Main/Work") { RootDirectoryPath = "root/dir" } },
        };

        private static JObject ShapeOf(string type, object options)
        {
            // What WriteableFileProvider<T>.ToJson writes: the options' public properties, then "Type".
            var ret = JObject.FromObject(options);
            ret["Type"] = type;
            return ret;
        }

        [TestMethod]
        [DynamicData(nameof(Shapes))]
        public void WrittenShapeMatchesGolden(string type, object options)
        {
            var golden = JObject.Parse(Golden(type + ".json"));
            var written = ShapeOf(type, options);
            Assert.IsTrue(JToken.DeepEquals(golden, written), $"Written: {written}");
        }

        [TestMethod]
        [DynamicData(nameof(Shapes))]
        public void GoldenReadsBackToTheSameOptions(string type, object options)
        {
            var read = JObject.Parse(Golden(type + ".json")).ToObject(options.GetType());
            AssertSameOptions(options, read, ignore: type == "WriteableAmazonS3FileProvider" ? "StorageClassForNewFiles" : null);
        }

        [TestMethod]
        public void S3StorageClassWrittenAsAnObjectIsLostOnRead()
        {
            // F78: the old serializer writes the storage class as {"Value":"STANDARD_IA"} but cannot read that form back,
            // so the default STANDARD silently replaces it. The string form reads correctly. The 2027 serializer reads
            // both forms and writes the string form; this test flips with it.
            var objectForm = (AmazonS3FileProviderOptions)JObject.Parse(Golden("WriteableAmazonS3FileProvider.json")).ToObject(typeof(AmazonS3FileProviderOptions));
            Assert.AreEqual("STANDARD", objectForm.StorageClassForNewFiles.Value);
            var stringForm = (AmazonS3FileProviderOptions)JObject.Parse(Golden("Lenient.AmazonS3.json")).ToObject(typeof(AmazonS3FileProviderOptions));
            Assert.AreEqual("STANDARD_IA", stringForm.StorageClassForNewFiles.Value);
        }

        [TestMethod]
        public void ProvidersThatConstructOfflineRoundTripThroughTheSerializer()
        {
            var assemblies = new[] { typeof(WriteableAzureBlobFileProvider).Assembly, typeof(WriteableMinioFileProvider).Assembly };
            // S3 is left out until F78 is fixed: its storage class does not survive the round trip.
            foreach (var shape in Shapes.Where(s => s[0] is "WriteableAzureBlobFileProvider" or "WriteableMinioFileProvider"))
            {
                var provider = WriteableFileProviderSerializer.FromJson(JObject.Parse(Golden(shape[0] + ".json")), assemblies);
                Assert.AreEqual(shape[0], provider.GetType().Name);
                Assert.IsTrue(JToken.DeepEquals(JObject.Parse(Golden(shape[0] + ".json")), WriteableFileProviderSerializer.ToJson(provider)));
            }
        }

        [TestMethod]
        public void LenientInputsReadLikeTheGolden()
        {
            // Inputs consumers may have stored by hand: other casing, a quoted bool, a numeric id, the root as a path only
            // or as segments only, unknown keys. The old serializer reads them; the new one must too.
            var minio = (MinioFileProviderOptions)JObject.Parse(Golden("Lenient.Minio.json")).ToObject(typeof(MinioFileProviderOptions));
            Assert.IsTrue(minio.UseSSL);
            Assert.AreEqual("minio.example.net:9000", minio.HostAndPort);
            CollectionAssert.AreEqual(new[] { "root", "dir" }, minio.RootDirectorySegments);

            var box = (BoxFileProviderOptions)JObject.Parse(Golden("Lenient.Box.json")).ToObject(typeof(BoxFileProviderOptions));
            Assert.AreEqual("123456", box.EnterpriseId);
            Assert.AreEqual("0", box.RootFolderId);
            CollectionAssert.AreEqual(new[] { "a", "b" }, box.RootDirectorySegments);
        }

        public static void AssertSameOptions(object expected, object actual, string ignore = null)
        {
            Assert.AreEqual(expected.GetType(), actual.GetType());
            foreach (var p in expected.GetType().GetProperties(BindingFlags.Public | BindingFlags.Instance).Where(p => p.CanRead && p.Name != ignore))
            {
                var e = p.GetValue(expected);
                var a = p.GetValue(actual);
                if (e is string[] es)
                    CollectionAssert.AreEqual(es, (string[])a, p.Name);
                else
                    Assert.AreEqual(e?.ToString(), a?.ToString(), p.Name);
            }
        }
    }
}
